import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const [source,target]=process.argv.slice(2);
await fs.cp(source,target,{recursive:true});
const file=path.join(target,'lib/ledger/github.mjs');
const before=await fs.readFile(file,'utf8');
const expression=/present\s*=\s*\(await issueQuery\(id,\s*projectField\)\)\.projectItems\.nodes\.some\(\s*\(?item\)?\s*=>\s*String\(item\.project\.number\)\s*===\s*String\(project\),?\s*\);/g;
assert.equal([...before.matchAll(expression)].length,1,'exactly one membership read must exist');
const after=before.replace(expression,'present=false;');assert.notEqual(after,before);
await fs.writeFile(file,after);
