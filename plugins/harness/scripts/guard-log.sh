#!/usr/bin/env bash
# guard.sh 발화 로그의 회차별 계수. 규칙이 실제로 몇 번 발화했는지를 기계값으로 낸다.
#
# 왜: 신규 게이트의 값어치를 판정하려면 "그 규칙이 최근 회차에서 발화한 적이 있는가" 가
# 기계값이어야 한다. 지금까지 그 수는 사람의 세션 기억뿐이었다
# (harness-pl7 S16).
#
# 출력: TSV 세 열 — <회차(session_id)> <규칙 또는 -> <횟수>. 정렬은 사전순.
#   r_main_write 처럼 규칙 이름이 든 행 = 그 규칙이 그 회차에서 그만큼 발화(차단)했다
#   `-` 행                              = 훅이 돌았고 아무 규칙도 발화하지 않은 호출 수
#   SKIP-nojq · SKIP-badjson 행         = 훅이 돌았지만 검사를 건너뛴 호출 수
#
# **발화 0 과 훅 미실행의 구분이 이 명령의 요점이다.** 그리고 부재에는 원인이 둘이다 —
# 그 둘이 같은 문구로 나오면 계수가 그 자리에서 거짓 근거가 된다 (harness-dg0.6.33).
#   발화 0        그 회차의 행이 있고 규칙 열이 `-` 뿐이다 (훅은 돌았다)
#   훅 미실행     rc=1. 로그가 없고, **배선된 guard.sh 에는 로깅 호출이 있다** —
#                 그러니 비어 있다는 것은 훅이 안 돌았다는 뜻이다
#   로깅 없는 판  rc=3. 로그가 없는데 **배선된 guard.sh 에 로깅 호출이 없다.** 훅은
#                 돌아도 아무것도 안 남는다. 이 상태의 빈 로그는 미실행도 발화 0 도
#                 아니다 — 전역 원장과 달리 **훅 코드는 트리 안에 있어 브랜치를 탄다**
#
# 어느 guard.sh 를 보는가: hooks.json 이 `${CLAUDE_PLUGIN_ROOT}/hooks/guard.sh` 를 부르므로
# (그 배선은 checks/guardrail-check.sh S2 가 단언한다) 같은 변수로 정한다. 변수가 없으면 이
# 스크립트 자신의 플러그인 트리로 떨어지는데 **그 트리가 세션이 배선한 트리와 다를 수 있다**
# — 그래서 검사한 훅 경로를 문구에 함께 낸다. 하네스 루트는 필요 없다 — 로그도 훅도 하네스 루트
# 밖($HOME·플러그인)에 있어 lib/harness-root.sh 를 부르지 않는다. 계수를 근거로
# 쓸 수 있는 조건과 이 셋의 천장은 ../docs/guardrail-verification.md 11절이 든다.
#
# 나머지 한계는 guard.sh 의 "발화 로그" 주석이 든다 (회차 정의·session_id 부재·회전 소실).
#
# ── 하위 명령 ──────────────────────────────────────────────────────────────
#   guard-log.sh                  회차 × 규칙 별 횟수 (위 출력. 기본값)
#   guard-log.sh count            같은 것
#   guard-log.sh rows [<회차>]    차단 행마다 분류에 쓸 축을 낸다
#
# **왜 rows 가 따로 있나.** 계수는 "몇 번 발화했나" 만 낸다. 그 발화가 정당했는지는 규칙
# 이름만으로 못 가른다 (guard.sh 의 deny 주석). rows 는 차단 행마다 판정 재료를 낼 뿐
# **분류하지는 않는다** — 자연어 판정이 필요한 비율이 47.4% 라(skills#224 실측) 이 자리가
# 하는 일은 사람의 읽기를 없애는 것이 아니라 그 앞까지를 기계가 해두는 것이다.
#
# 출력: TSV 일곱 열 — <시각> <회차> <에이전트> <도구> <규칙> <분류가능성> <명령>.
# 정렬하지 않는다(로그 순서 = 시간 순). 요약과 사유는 stderr 로 나가 stdout 은 기계값만 든다.
#
# **6열 분류가능성이 이 명령의 요점이다.** 로그는 명령을 120자에서 자르므로
# (guard.sh 의 `${ev:0:120}`) 잘린 행은 판정을 가르는 토큰이 로그 밖에 있다.
#   ok         명령 문자열이 온전하다 (120자 미만)
#   truncated  120자 상한에 걸렸다 — **분류 불가**
#   nocmd      옛 5열 행이라 명령 문자열 자체가 없다 — **분류 불가**
# 잘린 행을 정당으로도 오탐으로도 세면 안 된다. 그래서 분류 불가를 행마다 표시하고
# 아래 rc=6 이 "전부 분류 불가" 를 '오탐 0' 과 가른다.
#
# **절단을 넓히지 않은 이유** (이 자리의 설계 판단): 넓히려면 hooks/guard.sh 를 고쳐야
# 하는데 로그를 쓰는 것은 **설치된 플러그인 판**이지 이 트리가 아니다
# (../docs/guardrail-verification.md 11절 조건 1). 그래서 여기서 넓혀도 이미 쌓인 절단 행은
# 그대로고 새 행조차 릴리스·설치 뒤에야 는다 — 지금 분류할 표본에는 한 줄도 안 는다.
# 넓히는 것은 별도 판단이고 여기서는 **천장으로 기록**한다.
#
# [천장] truncated 는 "문자 길이가 120 이상" 이라는 추정이다. 정확히 120자인 온전한
# 명령도 걸리는데 **분류 불가 쪽으로 틀리는 방향**이라 그대로 둔다. 길이는 반드시
# **문자**로 센다 — awk 의 length() 는 이 환경에서 바이트라(실측: length("한글")=6)
# 바이트로 재면 한글 섞인 온전한 명령이 잘린 것으로 뒤집힌다.
#
# **세 가지 없음을 rc 가 가른다.** "0건" 과 "못 셌다" 가 같은 값이면 그 자리에서 거짓
# 근거가 된다 — 이 파일이 계수에서 이미 하는 구분(rc=1·3)의 rows 판이다.
#   rc=0   행이 나왔다
#   rc=1·3 로그가 없다 (원인 둘은 위 표대로 — 훅 미실행 / 로깅 없는 판)
#   rc=4   로그는 있고 이 범위의 차단이 **실제로 0** 이다
#   rc=5   준 회차의 행이 로그에 아예 없다 — 0 이 아니라 **회차를 못 찾았다**
#   rc=6   차단은 있는데 **전부 분류 불가**다 — '오탐 0' 이 아니라 못 셌다
#   rc=2   모르는 하위 명령
set -uo pipefail

# 하위 명령은 로그 부재 판정보다 **먼저** 검사한다 — 오타난 하위 명령이 로그 없음의
# rc=1 로 나오면 사람이 없는 상태를 고치러 간다.
CMD="${1:-count}"
SESS="${2-}"
case "${CMD}" in
  count) [ $# -le 1 ] || { printf '%s\n' "count 는 인자를 받지 않는다: $*" >&2; exit 2; } ;;
  rows)  [ $# -le 2 ] || { printf '%s\n' "rows 는 회차 하나만 받는다: $*" >&2; exit 2; } ;;
  *)     printf '%s\n' "모르는 하위 명령: ${CMD} — count | rows [<회차>]" >&2; exit 2 ;;
esac

# 기본 경로는 guard.sh 의 GUARD_LOG 와 **같은 표현이어야 한다** — 갈라지면 이 명령이 빈
# 로그를 보고 "훅 미실행" 이라고 거짓말한다. checks/guard-check.sh ⑮ 가 두 파일에서
# 기본값을 각각 파생해 대조한다 (한쪽만 고치면 게이트가 비-0).
LOG="${HARNESS_GUARD_LOG:-$HOME/.claude/harness-guard-log.tsv}"

if [ ! -s "${LOG}" ]; then
  HOOK="${CLAUDE_PLUGIN_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}/hooks/guard.sh"
  WHY="검사한 훅에는 로깅 호출이 있다"
  # 아래 if…fi 가 두 부재를 가르는 로직이다. 통째로 빼면 두 상태가 같은 문구로 돌아간다 —
  # checks/guard-check.sh ⑰ 이 이 범위만 지운 사본으로 그 귀속을 든다.
  if [ ! -r "${HOOK}" ]; then
    WHY="훅 파일을 읽지 못해 로깅 유무를 확인하지 못했다"
  elif ! grep -q '^[[:space:]]*log_guard ' "${HOOK}"; then
    printf '%s\n' "로깅 없는 guard.sh 가 발화 중이다 — 훅은 돌아도 로그를 남기지 않는다. 이 빈 로그는 '훅 미실행' 도 '발화 0' 도 아니다. 훅=${HOOK} 로그=${LOG}" >&2
    exit 3
  fi
  printf '%s\n' "발화 로그가 없거나 비었다 — 훅이 한 번도 돌지 않았다는 뜻이지 '발화 0' 이 아니다 (${WHY}: ${HOOK}): ${LOG}" >&2
  exit 1
fi

if [ "${CMD}" = "count" ]; then
  awk -F'\t' '{ c[$2 "\t" $5]++ } END { for (k in c) print k "\t" c[k] }' "${LOG}" | sort
  exit 0
fi

# 차단 행 = 규칙 열이 `-`(통과) 도 SKIP-*(검사 건너뜀) 도 아닌 행.
# 한글 문자열을 awk 의 ==/!= 로 비교하지 않는다 — macOS 기본 awk 가 다른 한글끼리를 같다고
# 낸다 (skills#224 부수 실측). 비교 값은 전부 ASCII 로 둔다.
awk -F'\t' -v sess="${SESS}" -v logpath="${LOG}" '
  # 이어지는 바이트(0x80~0xBF) 를 세어 빼면 문자 수다. awk 의 length() 가 바이트라
  # 이 표가 없으면 한글 섞인 온전한 명령이 절단으로 뒤집힌다.
  BEGIN { for (i = 128; i <= 191; i++) cont[sprintf("%c", i)] = 1 }
  function chars(s,   i, n, k) {
    n = length(s); k = 0
    for (i = 1; i <= n; i++) if (substr(s, i, 1) in cont) k++
    return n - k
  }
  sess != "" && $2 != sess { next }
  { seen++ }
  $5 == "-" || $5 ~ /^SKIP-/ { next }
  {
    state = (NF < 6 || $6 == "") ? "nocmd" : (chars($6) >= 120 ? "truncated" : "ok")
    cnt[state]++; blocked++
    print $1 "\t" $2 "\t" $3 "\t" $4 "\t" $5 "\t" state "\t" $6
  }
  END {
    if (sess != "" && seen == 0) {
      printf("회차 %s 의 행이 로그에 없다 — 차단 0건이 아니라 그 회차를 못 찾았다 (회전으로 사라졌거나 회차 이름이 다르다): %s\n", sess, logpath) > "/dev/stderr"
      exit 5
    }
    if (blocked == 0) {
      printf("차단 0건 — 이 범위의 %d줄이 전부 통과·SKIP 이다. 못 센 것이 아니라 차단이 실제로 0 이다: %s\n", seen, logpath) > "/dev/stderr"
      exit 4
    }
    printf("차단 %d건: 분류 가능 %d · 절단(120자 상한) %d · 명령 없음(옛 5열 행) %d\n", blocked, cnt["ok"] + 0, cnt["truncated"] + 0, cnt["nocmd"] + 0) > "/dev/stderr"
    if (cnt["ok"] + 0 == 0) {
      printf("차단 %d건이 전부 분류 불가다 — 이 범위로는 오탐률을 낼 수 없다. 오탐 0 이 아니라 못 셌다.\n", blocked) > "/dev/stderr"
      exit 6
    }
    exit 0
  }
' "${LOG}"
